from PIL import ImageFont
FONTFILE = {(HEAD, True): "~/.fonts/Montserrat-Bold.ttf", (BODY, False): "~/.fonts/SourceSans3-Regular.ttf",
            (GARA, False): "~/.fonts/EBGaramond-Italic.ttf"}
_F = {}


def nlines(t, pt, w, font, bold):
    """Real line count, measured with the font files (emoji measured as one wide glyph)."""
    k = (font, bold, pt)
    if k not in _F: _F[k] = ImageFont.truetype(os.path.expanduser(FONTFILE[(font, bold)]), int(pt * 1.3333))
    f = _F[k]; n = 0
    for para in t.split("\n"):
        n += 1; cur = ""
        for word in para.split(" "):
            trial = (cur + " " + word).strip()
            if cur and f.getlength(trial) > w * 0.97: n += 1; cur = word
            else: cur = trial
    return n


def fit(t, w, h, sizes, font=HEAD, bold=True, sp=1.12):
    for pt in sizes:
        hh = nlines(t, pt, w, font, bold) * pt * 1.3333 * 1.17 * sp
        if hh <= h: return pt, hh
    pt = sizes[-1]; return pt, nlines(t, pt, w, font, bold) * pt * 1.3333 * 1.17 * sp


def words(s, t, x, y, w, h, color=INK, sizes=(56, 52, 48, 44, 40, 36, 32), font=HEAD, bold=True, anchor="t", sp=1.12, italic=False):
    pt, th_ = fit(t, w, h, sizes, font, bold, sp)
    yy = y + (h - th_) / 2 if anchor == "m" else y
    text(s, x, yy, w, th_ + 20, t, pt, color, font, bold, italic=italic, spacing=sp)
    return yy + th_


# ---------------------------------------------------------------- slide furniture
class Post:
    def __init__(self, name, folder="november", w=1080, h=1350):
        self.name, self.folder, self.W, self.H = name, folder, w, h
        self.d = Deck(w, h, name=name)

    def slide(self, bg, note):
        return self.d.slide(bg, note + " " + RULES, counter=False)

    def save(self):
        path = os.path.join(ROOT, "templates", "posts", self.folder, self.name + ".pptx")
        if PREVIEW: path = os.path.join(TMP, "preview", self.folder, self.name + ".pptx")
        self.d.finish(path, counters=False)
        print("wrote", os.path.relpath(path, ROOT))
        return path


def furniture(p, s, dark, first=False, last=False, source=None, series=True):
    """Series label top left; source line bottom left; logo on the first and last slide, soilfoodweb.com otherwise."""
    W, H = p.W, p.H
    fg = CREAM if dark else GREEN
    if series:
        text(s, 80, 70, W - 160, 30, SERIES, 18, GLOW if dark else GREEN, HEAD, True, track=2)
    if source:
        text(s, 80, H - 92, W - 80 - 80 - 300, 50, source, 16, CREAM if dark else FAINT, BODY, alpha=80 if dark else None, spacing=1.05)
    if first or last:
        logo(s, W - 80 - 110, H - 70 - 110 * 668 / 743, 110, white=dark)
    else:
        text(s, W - 80 - 260, H - 88, 260, 30, "soilfoodweb.com", 18, fg, HEAD, True, align="r")


def t3(p, t, rel=None, note="", source=None, first=False, last=False, step=None, photo_rel=None, img_h=560, focus=(0.5, 0.5)):
    """Template 3 item: words on cream, then the picture. Optional big step number."""
    s = p.slide(CREAM, "Template 3. " + note)
    y = 150
    if step:
        text(s, 80, 120, 200, 180, step, 150, GREEN, HEAD, True, spacing=0.9); y = 320
    has_img = rel or photo_rel
    th_ = (p.H - 160 - img_h - 40) - y if has_img else p.H - 260 - y
    words(s, t, 80, y, p.W - 160, th_, INK, anchor="t" if has_img else "m")
    if photo_rel is not None:
        photo(s, photo_rel, 80, p.H - 160 - img_h, p.W - 160, img_h, *focus)
    elif rel:
        art(s, rel, 80, p.H - 160 - img_h, p.W - 160, img_h)
    furniture(p, s, False, first, last, source)
    return s


