def picture(s, path, x, y, w, h):
    sh = s.shapes.add_picture(path, Emu(int(x * PX)), Emu(int(y * PX)), Emu(int(w * PX)), Emu(int(h * PX)))
    return sh


def logo(s, x, y, w, white):
    return picture(s, os.path.join(ROOT, LOGO_WHITE if white else LOGO_COLOR), x, y, w, w * 668 / 743)


def trimmed(rel):
    os.makedirs(TMP, exist_ok=True)
    out = os.path.join(TMP, "trim-" + os.path.basename(rel))
    im = Image.open(os.path.join(ROOT, rel)).convert("RGBA")
    box = im.split()[3].point(lambda v: 255 if v > 20 else 0).getbbox()
    im.crop(box).save(out)
    return out


def art(s, rel, x, y, w, h):
    """Cutout (collage or microscopy) fitted inside the box, centred, straight. Placeholder if it does not exist."""
    if not os.path.exists(os.path.join(ROOT, rel)):
        MISSING.append(rel)
        return placeholder(s, x, y, w, h, "COLLAGE: " + os.path.basename(rel))
    p = trimmed(rel); iw, ih = Image.open(p).size; r = min(w / iw, h / ih)
    return picture(s, p, x + (w - iw * r) / 2, y + (h - ih * r) / 2, iw * r, ih * r)


def photo(s, rel, x, y, w, h, fx=0.5, fy=0.5):
    if not rel or not os.path.exists(os.path.join(ROOT, rel)):
        return placeholder(s, x, y, w, h, "PHOTO: " + (rel or "needed"))
    return picture(s, crop(rel, int(w), int(h), fx, fy), x, y, w, h)


