    text(s, 70, top, 300, 260, "“", 260, GLOW, GARA, False, spacing=0.8)
    end = words(s, quote, 80, top + 220, p.W - 160, 560, CREAM, sizes=(pt,), font=GARA, bold=False, sp=1.15, italic=True)
